import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = process.env.AZRI_LP_ROOT || fileURLToPath(new URL('../', import.meta.url));
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const page = read('index.html');
const start = page.indexOf('      <div class="contact-card">');
const end = page.indexOf('\n    </section>\n  </main>', start);
if (start < 0 || end < start) throw new Error('Contact card not found');
const card = page.slice(start, end).replace('href="#top"', 'href="https://azri-corp.com/#top" target="_top"');
const styles = read('style.css').slice(0, read('style.css').indexOf('.header'));
const shared = ['.eyebrow ', '.button ', '.button:hover ', '.text-link '].map(prefix => read('style.css').split('\n').find(line => line.startsWith(prefix))).join('\n');
const form = `<!doctype html>
<html lang="ja"><head><base target="_top"><meta charset="utf-8"><title>AZRI お問い合わせ</title>
<style>${styles}\n${shared}\n${read('contact.css')}
html,body{margin:0;padding:0;background:transparent}body{padding-bottom:4px}.contact-card{max-width:none;box-shadow:none}.button{min-width:0}a{color:inherit;text-decoration:none}[hidden]{display:none!important}
@media(prefers-reduced-motion:reduce){*{transition:none!important}}
</style></head><body>
<p id="contact-connection" class="contact-notice">フォームを接続しています。AZRIのサイトからご利用ください。</p>
${card}
<script>window.AZRI_CONTACT={hosted:true,sessionToken:<?!= JSON.stringify(sessionToken) ?>,parentOrigin:<?!= JSON.stringify(parentOrigin) ?>,frameId:<?!= JSON.stringify(frameId) ?>};</script>
<script>${read('contact.js')}</script>
<script>${read('apps-script/bridge.js')}</script>
</body></html>`;
fs.writeFileSync(path.join(root, 'apps-script/Form.html'), form);
fs.writeFileSync(path.join(root, 'apps-script/Deploy.gs'), '// GENERATED by scripts/build-apps-script.mjs. Paste this entire file into Apps Script.\n' + read('apps-script/Code.gs') + '\nconst CONTACT_FORM_HTML = ' + JSON.stringify(form) + ';\n');
console.log('Built self-contained Apps Script deployment source (no credentials).');
